const fs = require('fs');
const path = require('path');
const solc = require('solc');

const contractPath = path.resolve(__dirname, '../contracts/ProductWarrantyRegistry.sol');
const source = fs.readFileSync(contractPath, 'utf8');

const input = {
  language: 'Solidity',
  sources: {
    'ProductWarrantyRegistry.sol': {
      content: source,
    },
  },
  settings: {
    optimizer: {
      enabled: true,
      runs: 200,
    },
    outputSelection: {
      '*': {
        '*': ['abi', 'evm.bytecode.object'],
      },
    },
  },
};

console.log('Compiling ProductWarrantyRegistry.sol...');
const output = JSON.parse(solc.compile(JSON.stringify(input)));

if (output.errors) {
  let hasError = false;
  for (const err of output.errors) {
    console.log(err.formattedMessage);
    if (err.severity === 'error') hasError = true;
  }
  if (hasError) process.exit(1);
}

const contract = output.contracts['ProductWarrantyRegistry.sol']['ProductWarrantyRegistry'];
const abi = contract.abi;
const bytecode = '0x' + contract.evm.bytecode.object;

const outDir = path.resolve(__dirname, '../src/contracts');
fs.mkdirSync(outDir, { recursive: true });

const tsContent = `// Auto-generated by scripts/compile.cjs — ProductWarrantyRegistry on Botchain Testnet (Chain ID 968)
export const PRODUCT_WARRANTY_REGISTRY_ABI = ${JSON.stringify(abi, null, 2)} as const;

export const PRODUCT_WARRANTY_REGISTRY_BYTECODE = "${bytecode}" as \`0x\${string}\`;
`;

fs.writeFileSync(path.join(outDir, 'ProductWarrantyRegistryABI.ts'), tsContent, 'utf8');
console.log('Successfully generated src/contracts/ProductWarrantyRegistryABI.ts');

